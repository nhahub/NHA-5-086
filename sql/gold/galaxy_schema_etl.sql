-- ---- fact_sales (cost from the actual inventory unit, fallback to product cost) ----
INSERT INTO gold.fact_sales
SELECT oi.id,
       oi.order_id,
       oi.inventory_item_id,
       du.user_key,
       dp.product_key,
       TO_CHAR(o.created_at, 'YYYYMMDD')::INT,
       COALESCE(TO_CHAR(o.shipped_at,   'YYYYMMDD')::INT, -1),
       COALESCE(TO_CHAR(o.delivered_at, 'YYYYMMDD')::INT, -1),
       COALESCE(TO_CHAR(o.returned_at,  'YYYYMMDD')::INT, -1),
       o.status,
       oi.sale_price,
       COALESCE(ii.cost, p.cost),
       oi.sale_price - COALESCE(ii.cost, p.cost)
FROM silver.order_items oi
JOIN silver.orders o                  ON o.order_id   = oi.order_id
JOIN silver.products p                ON p.id         = oi.product_id
JOIN gold.dim_user du           ON du.user_id   = o.user_id
JOIN gold.dim_product dp        ON dp.product_id = oi.product_id
LEFT JOIN silver.inventory_items ii   ON ii.id        = oi.inventory_item_id;

-- ---- fact_inventory ----
INSERT INTO gold.fact_inventory
SELECT ii.id,
       dp.product_key,
       dc.dc_key,
       TO_CHAR(ii.created_at, 'YYYYMMDD')::INT,
       COALESCE(TO_CHAR(ii.sold_at, 'YYYYMMDD')::INT, -1),
       ii.cost,
       ii.available,
       CASE WHEN ii.sold_at IS NULL THEN 0 ELSE 1 END
FROM silver.inventory_items ii
JOIN gold.dim_product dp             ON dp.product_id = ii.product_id
JOIN gold.dim_distribution_center dc ON dc.dc_id      = ii.product_distribution_center_id;

-- ---- fact_events ----
-- one location_key per (city, state, postal_code) to avoid duplicating events
CREATE TEMP TABLE loc_map AS
SELECT city, state, postal_code, MIN(location_key) AS location_key
FROM gold.dim_location
WHERE location_key <> -1
GROUP BY city, state, postal_code;

CREATE INDEX ON loc_map (city, state, postal_code);

INSERT INTO gold.fact_events
SELECT e.id,
       e.session_id,
       COALESCE(du.user_key, -1),                       -- guests -> -1
       COALESCE(dp.product_key, -1),                    -- non-product events -> -1
       COALESCE(lm.location_key, -1),
       ep.event_profile_key,
       TO_CHAR(e.created_at, 'YYYYMMDD')::INT,
       e.created_at,                                    -- event_ts
       e.sequence_number
FROM silver.events e
LEFT JOIN gold.dim_user du
       ON du.user_id = e.user_id
LEFT JOIN gold.dim_product dp
       ON dp.product_id = SUBSTRING(e.uri FROM '^/product/([0-9]+)')   -- adjust to your uri format
LEFT JOIN loc_map lm
       ON  lm.city        = COALESCE(NULLIF(e.city, 'null'), 'Unknown')
       AND lm.state       = COALESCE(e.state, 'Unknown')
       AND lm.postal_code = COALESCE(e.postal_code, 'Unknown')
JOIN gold.dim_event_profile ep
       ON  ep.event_type     = COALESCE(e.event_type, 'Unknown')
       AND ep.browser        = COALESCE(e.browser, 'Unknown')
       AND ep.traffic_source = COALESCE(e.traffic_source, 'Unknown');

-- =====================================================================
-- 5) VIEW (replaces the customer_activity table)
-- =====================================================================
CREATE OR REPLACE VIEW gold.vw_customer_activity AS
SELECT
    du.user_id,
    MIN(dd.full_date) AS first_order_date,
    MAX(dd.full_date) AS last_order_date,
    DATE '2022-06-08' - MAX(dd.full_date) AS days_since_last_order,

    CASE
        WHEN DATE '2022-06-08' - MAX(dd.full_date) < 365 THEN 1
        ELSE 0
    END::INT AS is_active

FROM gold.fact_sales fs
JOIN gold.dim_user du
    ON du.user_key = fs.user_key
JOIN gold.dim_date dd
    ON dd.date_key = fs.order_date_key

GROUP BY du.user_id;
-- dynamic reference date: replace DATE '2022-06-08' with CURRENT_DATE

