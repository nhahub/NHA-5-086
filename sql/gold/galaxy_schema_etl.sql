-- ---- dim_date ----
INSERT INTO gold.dim_date VALUES (-1, NULL, NULL, NULL, 'Unknown', NULL, NULL, 'Unknown');

INSERT INTO gold.dim_date
SELECT TO_CHAR(d, 'YYYYMMDD')::INT,
       d::DATE,
       EXTRACT(DAY     FROM d),
       EXTRACT(MONTH   FROM d),
       TO_CHAR(d, 'FMMonth'),
       EXTRACT(QUARTER FROM d),
       EXTRACT(YEAR    FROM d),
       TO_CHAR(d, 'FMDay')
FROM generate_series(
        (SELECT LEAST(
                    (SELECT MIN(created_at) FROM silver.users),
                    (SELECT MIN(created_at) FROM silver.orders),
                    (SELECT MIN(created_at) FROM silver.inventory_items),
                    (SELECT MIN(created_at) FROM silver.events)))::DATE,
        (SELECT GREATEST(
                    (SELECT MAX(created_at)   FROM silver.users),
                    (SELECT MAX(created_at)   FROM silver.orders),
                    (SELECT MAX(shipped_at)   FROM silver.orders),
                    (SELECT MAX(delivered_at) FROM silver.orders),
                    (SELECT MAX(returned_at)  FROM silver.orders),
                    (SELECT MAX(sold_at)      FROM silver.inventory_items),
                    (SELECT MAX(created_at)   FROM silver.events)))::DATE,
        INTERVAL '1 day') AS d;

-- ---- dim_location (users + events, "null" text cleaned to Unknown) ----
INSERT INTO gold.dim_location (location_key, city, state, country, postal_code)
OVERRIDING SYSTEM VALUE
VALUES (-1, 'Unknown', 'Unknown', 'Unknown', 'Unknown');

INSERT INTO gold.dim_location (city, state, country, postal_code)
SELECT DISTINCT
       COALESCE(NULLIF(city, 'null'), 'Unknown'),
       COALESCE(state, 'Unknown'),
       COALESCE(country, 'Unknown'),
       COALESCE(postal_code, 'Unknown')
FROM silver.users
ON CONFLICT DO NOTHING;

-- events has no country: add only combinations that users did not already cover
INSERT INTO gold.dim_location (city, state, country, postal_code)
SELECT DISTINCT
       COALESCE(NULLIF(e.city, 'null'), 'Unknown'),
       COALESCE(e.state, 'Unknown'),
       'Unknown',
       COALESCE(e.postal_code, 'Unknown')
FROM silver.events e
WHERE NOT EXISTS (
        SELECT 1 FROM gold.dim_location l
        WHERE l.city        = COALESCE(NULLIF(e.city, 'null'), 'Unknown')
          AND l.state       = COALESCE(e.state, 'Unknown')
          AND l.postal_code = COALESCE(e.postal_code, 'Unknown'))
ON CONFLICT DO NOTHING;

-- ---- dim_user ----
INSERT INTO gold.dim_user
    (user_key, user_id, full_name, age, age_group, gender,
     acquisition_source, created_date_key, location_key)
OVERRIDING SYSTEM VALUE
VALUES (-1, NULL, 'Guest', NULL, 'Unknown', 'Unknown', 'Unknown', -1, -1);

INSERT INTO gold.dim_user
    (user_id, full_name, age, age_group, gender,
     acquisition_source, created_date_key, location_key)
SELECT u.id,
       u.full_name,
       u.age,
       CASE WHEN u.age < 18 THEN '12-17'
            WHEN u.age < 25 THEN '18-24'
            WHEN u.age < 35 THEN '25-34'
            WHEN u.age < 45 THEN '35-44'
            WHEN u.age < 55 THEN '45-54'
            WHEN u.age < 65 THEN '55-64'
            ELSE '65+' END,
       u.gender,
       u.traffic_source,
       TO_CHAR(u.created_at, 'YYYYMMDD')::INT,
       dl.location_key
FROM silver.users u
JOIN gold.dim_location dl
  ON  dl.city        = COALESCE(NULLIF(u.city, 'null'), 'Unknown')
  AND dl.state       = COALESCE(u.state, 'Unknown')
  AND dl.country     = COALESCE(u.country, 'Unknown')
  AND dl.postal_code = COALESCE(u.postal_code, 'Unknown');

