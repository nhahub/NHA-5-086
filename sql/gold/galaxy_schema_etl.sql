-- =====================================================================
-- Galaxy Schema: CREATE TABLE + INSERT (PostgreSQL)
-- Source tables are in schema silver:
--   users, orders, order_items, products, inventory_items,
--   distribution_centers, events
-- Run the file top to bottom (order matters).
-- =====================================================================

-- 0) Schema (careful: DROP removes any previous warehouse in gold)
DROP SCHEMA IF EXISTS gold CASCADE;
CREATE SCHEMA gold;

-- =====================================================================
-- 1) DIMENSIONS - CREATE
-- =====================================================================

CREATE TABLE gold.dim_date (
    date_key    INT PRIMARY KEY,          -- 20220608, -1 = Unknown
    full_date   DATE,
    day         SMALLINT,
    month       SMALLINT,
    month_name  VARCHAR(20),
    quarter     SMALLINT,
    year        SMALLINT,
    weekday     VARCHAR(20)
);

CREATE TABLE gold.dim_location (
    location_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- -1 = Unknown
    city         VARCHAR(100),
    state        VARCHAR(100),
    country      VARCHAR(100),
    postal_code  VARCHAR(30),
    UNIQUE (city, state, country, postal_code)
);

CREATE TABLE gold.dim_user (
    user_key           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- -1 = Guest
    user_id            TEXT UNIQUE,
    full_name          VARCHAR(200),
    age                SMALLINT,
    age_group          VARCHAR(20),
    gender             VARCHAR(10),
    acquisition_source VARCHAR(50),   -- users.traffic_source
    created_date_key   INT REFERENCES gold.dim_date(date_key),
    location_key       INT REFERENCES gold.dim_location(location_key)
);

CREATE TABLE gold.dim_product (
    product_key  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- -1 = Unknown
    product_id   TEXT UNIQUE,
    name         TEXT,
    brand        VARCHAR(200),
    category     VARCHAR(100),
    department   VARCHAR(20),
    retail_price NUMERIC(12,2),
    cost         NUMERIC(12,2)
);

CREATE TABLE gold.dim_distribution_center (
    dc_key  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dc_id   TEXT UNIQUE,
    name    VARCHAR(100)
);

CREATE TABLE gold.dim_event_profile (
    event_profile_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type        VARCHAR(30),
    browser           VARCHAR(30),
    traffic_source    VARCHAR(30),
    UNIQUE (event_type, browser, traffic_source)
);

