CREATE TABLE gold.fact_sales (
    order_item_id      TEXT PRIMARY KEY,
    order_id           TEXT,            -- degenerate dimension
    inventory_item_id  TEXT,            -- degenerate dimension
    user_key           INT NOT NULL REFERENCES gold.dim_user(user_key),
    product_key        INT NOT NULL REFERENCES gold.dim_product(product_key),
    order_date_key     INT NOT NULL REFERENCES gold.dim_date(date_key),
    shipped_date_key   INT NOT NULL REFERENCES gold.dim_date(date_key),
    delivered_date_key INT NOT NULL REFERENCES gold.dim_date(date_key),
    returned_date_key  INT NOT NULL REFERENCES gold.dim_date(date_key),
    status             VARCHAR(20),
    sale_price         NUMERIC(12,2),
    cost               NUMERIC(12,2),
    profit             NUMERIC(12,2)
);

CREATE TABLE gold.fact_inventory (
    inventory_item_id TEXT PRIMARY KEY,
    product_key       INT NOT NULL REFERENCES gold.dim_product(product_key),
    dc_key            INT NOT NULL REFERENCES gold.dim_distribution_center(dc_key),
    created_date_key  INT NOT NULL REFERENCES gold.dim_date(date_key),
    sold_date_key     INT NOT NULL REFERENCES gold.dim_date(date_key),
    cost              NUMERIC(12,2),
    available         INT,
    is_sold           SMALLINT
);

CREATE TABLE gold.fact_events (
    event_id          TEXT PRIMARY KEY,
    session_id        TEXT,             -- degenerate dimension
    user_key          INT NOT NULL REFERENCES gold.dim_user(user_key),
    product_key       INT NOT NULL REFERENCES gold.dim_product(product_key),
    location_key      INT NOT NULL REFERENCES gold.dim_location(location_key),
    event_profile_key INT NOT NULL REFERENCES gold.dim_event_profile(event_profile_key),
    date_key          INT NOT NULL REFERENCES gold.dim_date(date_key),
    event_ts          TIMESTAMP,        -- source column: events.created_at
    sequence_number   SMALLINT
);

